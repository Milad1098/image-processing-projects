"""Clean speed measurement, separate from the accuracy run. Appends to docs/RESULTS.md.

    python -m experiments.speed

The accuracy run times every image as it goes, so its numbers include model loading
and whatever else the machine was doing. Here each model gets one fixed 800×600 photo,
two warm-up runs, then the median of repeated runs. "1 thread" approximates a browser
or a phone, which cannot use all cores of a laptop.
"""

import time
from pathlib import Path

import numpy as np
import onnxruntime as ort
from skimage import data

from bgremove import MODELS, grabcut
from bgremove import models as m

OUT = Path(__file__).resolve().parent.parent / "docs" / "RESULTS.md"
MARK = "## Speed"
RUNS = {"u2netp": 10, "silueta": 10, "modnet": 10, "isnet": 5, "birefnet-lite": 3}


def photo() -> np.ndarray:
    import cv2
    return cv2.resize(data.astronaut(), (800, 600), interpolation=cv2.INTER_AREA)


def timed(fn, runs: int) -> float:
    fn(), fn()                                   # warm-up: first runs allocate and optimize
    times = []
    for _ in range(runs):
        t = time.perf_counter()
        fn()
        times.append(time.perf_counter() - t)
    # minimum, not median: interference from other processes only ever adds time
    return min(times) * 1000


def best_of_two(name: str, threads: int | None) -> float:
    """The first model measured after start-up ran ~5x slow (CPU not yet at full clock);
    measuring every model twice with a fresh session and keeping the faster result removes it."""
    return min(timed(predictor(name, threads), RUNS[name]) for _ in range(2))


def predictor(name: str, threads: int | None):
    opts = ort.SessionOptions()
    if threads:
        opts.intra_op_num_threads = threads
    sess = ort.InferenceSession(str(m.MODELS_DIR / MODELS[name].file), opts, providers=["CPUExecutionProvider"])
    spec, img = MODELS[name], photo()
    feed = {sess.get_inputs()[0].name: m.preprocess(img, spec)}
    return lambda: m.postprocess(sess.run(None, feed)[0], spec, *img.shape[:2])


def main() -> None:
    img = photo()
    rows = [f"| grabcut | — | {min(timed(lambda: grabcut(img), 5) for _ in range(2)):,.0f} ms | — |"]
    for name in MODELS:
        all_cores = best_of_two(name, None)
        one = best_of_two(name, 1)
        size = (m.MODELS_DIR / MODELS[name].file).stat().st_size / 1e6
        rows.append(f"| {name} | {size:.0f} MB | {all_cores:,.0f} ms | {one:,.0f} ms |")
        print(rows[-1], flush=True)

    section = "\n".join([
        MARK, "",
        f"Generated by `python -m experiments.speed`. One 800×600 photo, 2 warm-up runs, fastest of 3–10 runs, best of two fresh sessions (other processes only add time, so the minimum is the cleanest estimate), "
        f"inference + pre/post-processing, onnxruntime {ort.__version__} on CPU.", "",
        "| method | size | all cores | 1 thread |", "|---|---|---|---|", *rows, ""])
    text = OUT.read_text(encoding="utf-8")
    text = text.split(MARK)[0].rstrip() + "\n\n" + section
    OUT.write_text(text, encoding="utf-8")
    print(f"written: {OUT}")


if __name__ == "__main__":
    main()
