"""Can the browser models' edges be cleaned up cheaply? Appends to docs/RESULTS.md.

    python -m experiments.refine

Two refinements of the upscaled matte: edge tightening and a guided filter. Parameters are
tuned on a *separate* sample (seed 1) and the chosen settings are reported on the benchmark
sample (seed 0): tuning on the images you report on would flatter the result. Images are
used at native resolution, because the halo comes from upscaling the matte.
"""

import statistics
from pathlib import Path

from bgremove import predict
from bgremove.metrics import boundary_f, iou, mae
from bgremove.refine import guided, tighten
from experiments import run

OUT = Path(__file__).resolve().parent.parent / "docs" / "RESULTS.md"
MARK = "## Edge refinement"
MODELS = ("modnet", "u2netp")          # the two models the browser app ships
TIGHTEN_GRID = [(0.1, 0.9), (0.2, 0.8), (0.3, 0.7)]
GUIDED_GRID = [(r, e) for r in (0.005, 0.01, 0.02) for e in (1e-4, 1e-3, 1e-2)]
TUNE_N = 40
NATIVE = 10_000


def scores(items, fn):
    """Mean (IoU, MAE, Boundary F) after applying fn(img, alpha) to each matte."""
    rows = [(iou(a, gt), mae(a, gt), boundary_f(a, gt)) for a, gt in ((fn(img, al), gt) for img, gt, al in items)]
    return tuple(statistics.fmean(c) for c in zip(*rows))


def with_mattes(images, model):
    return [(img, gt, predict(model, img)) for _, img, gt in images]


def main() -> None:
    run.MAX_SIDE = NATIVE
    portraits, objects = run.DATASETS["P3M-500 (portraits)"], run.DATASETS["DUTS-TE (objects)"]

    run.SEED, run.N = 1, TUNE_N
    tune_images = run.sample(portraits)
    tune_ids = {i for i, *_ in tune_images}
    tune = with_mattes(tune_images, "modnet")
    # tighten changes only the soft band, so tune it on MAE; the guided filter on Boundary F
    t_best = min(TIGHTEN_GRID, key=lambda p: scores(tune, lambda img, a: tighten(a, *p))[1])
    g_best = max(GUIDED_GRID, key=lambda p: scores(tune, lambda img, a: guided(img, a, *p))[2])
    print("tuned:", t_best, g_best, flush=True)

    run.SEED, run.N = 0, 100
    variants = {"none": lambda img, a: a,
                f"tighten {t_best}": lambda img, a: tighten(a, *t_best),
                f"guided r={g_best[0]}, ε={g_best[1]:g}": lambda img, a: guided(img, a, *g_best)}
    rows, overlap = [], 0
    for ds_name, path in (("P3M-500 (portraits)", portraits), ("DUTS-TE (objects)", objects)):
        images = run.sample(path)
        if path == portraits:
            overlap = len(tune_ids & {i for i, *_ in images})
        for model in MODELS:
            items = with_mattes(images, model)
            for name, fn in variants.items():
                s = scores(items, fn)
                rows.append(f"| {ds_name} | {model} | {name} | {s[0]:.3f} | {s[1]:.4f} | {s[2]:.3f} |")
                print(rows[-1], flush=True)

    section = "\n".join([
        MARK, "",
        f"Generated by `python -m experiments.refine`. Settings tuned on {TUNE_N} other portraits (seed 1; "
        f"{overlap} of them also in the benchmark sample), reported on the benchmark sample (seed 0) at "
        f"native resolution. Tightening maps matte values below the first number to 0 and above the second to 1.", "",
        "| test set | model | refinement | IoU ↑ | MAE ↓ | Boundary F ↑ |", "|---|---|---|---|---|---|", *rows, ""])
    text = OUT.read_text(encoding="utf-8")
    head, _, rest = text.partition(MARK)
    tail = rest.partition("\n## ")[2]
    OUT.write_text(head.rstrip() + "\n\n" + section + ("\n## " + tail if tail else ""), encoding="utf-8")
    print(f"written: {OUT}")


if __name__ == "__main__":
    main()
