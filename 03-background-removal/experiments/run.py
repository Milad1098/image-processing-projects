"""Benchmark every method on two public test sets. Writes docs/RESULTS.md.

    pip install -r requirements-dev.txt
    python -m experiments.download        # models + test sets (~1 GB)
    python -m experiments.run             # ~45 min on a laptop CPU; per-image results are cached

Test sets (evaluation only, never redistributed):
  DUTS-TE     5,019 photos of everyday objects with hand-drawn masks (salient object detection)
  P3M-500-NP  500 portraits with alpha mattes (portrait matting, faces not blurred)
A fixed-seed random sample of N images is drawn from each.
"""

import csv
import platform
import statistics
import time
from pathlib import Path

import cv2
import numpy as np
import onnxruntime as ort
import pyarrow.parquet as pq

from bgremove import MODELS, grabcut, predict
from bgremove.metrics import boundary_f, iou, mae
from bgremove.models import MODELS_DIR, session

ROOT = Path(__file__).resolve().parent.parent
DATASETS = {"DUTS-TE (objects)": ROOT / "data" / "duts-te.parquet",
            "P3M-500 (portraits)": ROOT / "data" / "p3m-500-np.parquet"}
N, SEED = 100, 0
METHODS = ["grabcut", *MODELS]
CACHE = ROOT / "data" / "results.csv"
OUT = ROOT / "docs" / "RESULTS.md"
FIELDS = ["dataset", "index", "method", "iou", "mae", "bf", "ms"]


MAX_SIDE = 1024   # P3M photos are up to ~2000 px; every model works at ≤ 1024 anyway


def sample(path: Path) -> list[tuple[int, np.ndarray, np.ndarray]]:
    """The fixed-seed sample, read batch by batch so the whole file never sits in memory."""
    pf = pq.ParquetFile(path)
    picks = set(np.random.default_rng(SEED).choice(pf.metadata.num_rows, min(N, pf.metadata.num_rows), replace=False).tolist())
    out, offset = [], 0
    for batch in pf.iter_batches(batch_size=32):
        for j, row in enumerate(batch.to_pylist()):
            if offset + j not in picks:
                continue
            img = cv2.imdecode(np.frombuffer(row["image"]["bytes"], np.uint8), cv2.IMREAD_COLOR)
            gt = cv2.imdecode(np.frombuffer(row["mask"]["bytes"], np.uint8), cv2.IMREAD_GRAYSCALE)
            scale = min(1.0, MAX_SIDE / max(img.shape[:2]))
            if scale < 1:
                size = (round(img.shape[1] * scale), round(img.shape[0] * scale))
                img = cv2.resize(img, size, interpolation=cv2.INTER_AREA)
                gt = cv2.resize(gt, size, interpolation=cv2.INTER_AREA)
            out.append((offset + j, cv2.cvtColor(img, cv2.COLOR_BGR2RGB), gt.astype(np.float32) / 255))
        offset += len(batch)
    return out


def load_cache() -> dict[tuple, dict]:
    if not CACHE.exists():
        return {}
    with CACHE.open(newline="") as f:
        return {(r["dataset"], int(r["index"]), r["method"]): r for r in csv.DictReader(f)}


def evaluate() -> dict[tuple, dict]:
    done = load_cache()
    new_file = not CACHE.exists()
    with CACHE.open("a", newline="") as f:
        writer = csv.DictWriter(f, FIELDS)
        if new_file:
            writer.writeheader()
        for ds, path in DATASETS.items():
            images = sample(path)
            for method in METHODS:                 # outer loop on methods: one model in memory at a time
                todo = [(i, img, gt) for i, img, gt in images if (ds, i, method) not in done]
                for n, (i, img, gt) in enumerate(todo, 1):
                    t = time.perf_counter()
                    alpha = grabcut(img) if method == "grabcut" else predict(method, img)
                    ms = (time.perf_counter() - t) * 1000
                    row = {"dataset": ds, "index": i, "method": method, "iou": f"{iou(alpha, gt):.4f}",
                           "mae": f"{mae(alpha, gt):.4f}", "bf": f"{boundary_f(alpha, gt):.4f}", "ms": f"{ms:.0f}"}
                    writer.writerow(row)
                    f.flush()
                    done[(ds, i, method)] = row
                    if n % 20 == 0 or n == len(todo):
                        print(f"{ds} · {method}: {n}/{len(todo)}", flush=True)
                session.cache_clear()              # free the model before the next one loads
    return done


def size_mb(method: str) -> str:
    return "—" if method == "grabcut" else f"{(MODELS_DIR / MODELS[method].file).stat().st_size / 1e6:.0f} MB"


def report(results: dict[tuple, dict]) -> str:
    lines = [
        "# Benchmark results",
        "",
        "_Generated by `python -m experiments.run`; do not edit by hand._",
        "",
        f"{N} images per test set (random, seed {SEED}), longer side scaled to ≤ {MAX_SIDE} px. Mean over images. "
        f"Speed is measured separately (see the last section): timings taken during this run were too "
        f"noisy to report. CPU: {platform.processor() or platform.machine()}, onnxruntime {ort.__version__}, "
        f"OpenCV {cv2.__version__}.",
        "",
        "IoU: mask overlap (higher is better). MAE: mean absolute error of the soft matte (lower is better). "
        "Boundary F: how well the outline matches within ~0.75% of the image diagonal (higher is better).",
    ]
    for ds in DATASETS:
        lines += ["", f"## {ds}", "", "| method | size | IoU ↑ | MAE ↓ | Boundary F ↑ |", "|---|---|---|---|---|"]
        for m in METHODS:
            rows = [r for (d, _, mm), r in results.items() if d == ds and mm == m]
            if not rows:
                continue
            mean = lambda k: statistics.fmean(float(r[k]) for r in rows)
            lines.append(f"| {m} | {size_mb(m)} | {mean('iou'):.3f} | {mean('mae'):.3f} | {mean('bf'):.3f} |")
    return "\n".join(lines) + "\n"


def main() -> None:
    # keep the section written by experiments/speed.py
    _, mark, speed = OUT.read_text(encoding="utf-8").partition("## Speed") if OUT.exists() else ("", "", "")
    OUT.write_text(report(evaluate()) + ("\n" + mark + speed if mark else ""), encoding="utf-8")
    print(f"written: {OUT}")


if __name__ == "__main__":
    main()
